insert into public.property_images (property_id, image_url, alt_text, order_index, is_cover)
select p.id, p.cover_image, p.title, 0, true
from public.properties p
where p.cover_image is not null
on conflict do nothing;

insert into public.property_features (property_id, name)
select p.id, feature.name
from public.properties p
cross join lateral unnest(p.characteristics) as feature(name)
on conflict (property_id, name) do nothing;
